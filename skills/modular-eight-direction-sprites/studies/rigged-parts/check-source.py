"""Reopen the actual .blend and inspect its baked action without manual posing."""
import bpy,json,math
import os
from pathlib import Path
from mathutils import Vector
HERE=Path(__file__).resolve().parent
OUT=Path(os.environ.get('SPRITE_OUTPUT_ROOT', str(HERE.parents[3]/'research/sprite-animation/silver-scarf/rig-proof-v4'))).resolve()
bpy.ops.wm.open_mainfile(filepath=str(OUT/'silver-scarf-modular-source.blend'))
rig=bpy.data.objects['SilverScarfRig'];scene=bpy.context.scene
data=json.loads((OUT/'rig-poses.json').read_text())
assert rig.data.bones['weapon.right'].parent.name=='right.hand'
objects=[o for o in scene.objects if 'part_id' in o]
weapon_objects=[o for o in objects if o['part_id'].startswith('weapon.')]
assert weapon_objects
for obj in weapon_objects:
 assert [g.name for g in obj.vertex_groups]==['weapon.right'],obj.name
 for vertex in obj.data.vertices:
  assert len(vertex.groups)==1 and abs(vertex.groups[0].weight-1)<1e-6
checks=[]
for key,ms in zip(data['keys'],data['times_ms']):
 scene.frame_set(ms+1);bpy.context.view_layer.update()
 grip=rig.pose.bones['weapon.right'].matrix.translation
 target=key['arms']['right']['end'];expected=Vector((target[0],-target[1],target[2]))
 error=(grip-expected).length
 owner_error=(grip-rig.pose.bones['right.hand'].matrix.translation).length
 assert error<1e-5 and owner_error<1e-5,(ms,error,owner_error)
 checks.append({'time_ms':ms,'baked_grip_error_world':error,'hand_parent_error_world':owner_error})
curves=rig.animation_data.action.fcurves
assert all(k.interpolation=='CONSTANT' for c in curves for k in c.keyframe_points)
report={'blender':bpy.app.version_string,'reopened_editable_source':True,'manual_pose_assignment_in_check':False,'bones':len(rig.data.bones),'weapon_parent':rig.data.bones['weapon.right'].parent.name,'weapon_meshes':len(weapon_objects),'weapon_weights':'Every weapon vertex is weighted 1.0 to weapon.right only','baked_keys':checks,'key_interpolation':'CONSTANT','geometry_objects':len(objects),'part_items':len(set(o['part_id'] for o in objects)),'scope':'Source attachment and baked key checks; not artistic acceptance. Dynamic trail geometry is generated by the exporter, not baked into this .blend action.'}
(OUT/'source-rig-check.json').write_text(json.dumps(report,indent=2)+'\n')
print('BAKED_SOURCE_CHECK_PASS',len(checks),max(c['baked_grip_error_world'] for c in checks),flush=True)
